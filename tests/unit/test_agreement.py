"""The agreement report: counts, the verdict table, and how disagreements are shown."""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

import pytest

from forge.core.types import ExecResult
from forge.eval.agreement import (
    AgreementRun,
    ItemScore,
    agreement_rate,
    group_repeats,
    render_report,
)
from forge.eval.mutations import Mutation, MutationKind

ROOT = Path(__file__).resolve().parents[2]

RUN = AgreementRun(
    command="forge eval agreement --mutations 3 --split val --seed 0",
    split="val",
    examples=2,
    databases=1,
    seed=0,
    day=date(2026, 11, 14),
    git_sha="0123456789abcdef0123456789abcdef01234567",
    data_hash="ab" * 32,
)


def _item(
    number: int,
    kind: MutationKind,
    fast: bool,
    official: bool,
    pred: ExecResult,
    *,
    pred_sql: str | None = None,
) -> ItemScore:
    gold_sql = "SELECT DISTINCT name FROM t WHERE x > 1"
    return ItemScore(
        mutation=Mutation(
            f"spider-train-{number:05d}",
            "db",
            kind,
            gold_sql,
            pred_sql if pred_sql is not None else f"{gold_sql} -- {number}",
        ),
        gold=ExecResult(ok=True, columns=["name"], rows=[("a",), ("b",)]),
        pred=pred,
        order_matters=False,
        fast=fast,
        official=official,
    )


@pytest.mark.phase(1)
def test_report_counts_and_lists_disagreements() -> None:
    many = ExecResult(ok=True, columns=["name"], rows=[(str(i),) for i in range(8)], truncated=True)
    failed = ExecResult(ok=False, error="no such column: y", error_kind="no_such_column")
    scores = [
        _item(1, "unchanged", True, True, ExecResult(ok=True, columns=["name"], rows=[("a",)])),
        _item(2, "drop_where", True, False, many),
        _item(3, "swap_column", False, False, failed),
    ]

    report = render_report(scores, RUN)

    assert agreement_rate(scores) == pytest.approx(2 / 3)
    lines = report.splitlines()
    assert lines[0] == "# Fast and official execution match agree on 66.67% of 3 items"
    assert f"Generated by `{RUN.command}` on 2026-11-14." in lines
    assert "| Split | val: 2 questions over 1 database |" in lines
    assert "| Agreement | 66.67% (2 of 3); I5 needs 98% |" in lines
    assert "| Distinct items | 3 |" in lines
    assert "| Agreement on distinct items | 66.67% (2 of 3) |" in lines
    assert f"| Git commit | `{RUN.git_sha}` |" in lines
    assert "| fast match | 1 (1) | 1 (1) |" in lines
    assert "| fast no match | 0 (0) | 1 (1) |" in lines
    assert "| drop_where | 1 (1) | 1 (1) | 0 (0) | 1 (1) |" in lines
    assert "| swap_column | 1 (1) | 0 (0) | 0 (0) | 0 (0) |" in lines
    assert "| unchanged | 1 (1) | 1 (1) | 1 (1) | 0 (0) |" in lines

    disagreements = report.split("## Disagreements\n", 1)[1]
    assert "Disagreeing items: 1 (1 distinct), each shown once below." in report
    assert disagreements.count("\n### ") == 1
    assert "### 1. spider-train-00002 on db: drop_where, fast match, official no match" in report
    assert "SELECT DISTINCT name FROM t WHERE x > 1 -- 2\n" in disagreements
    assert "columns: name; 2 rows\n('a',)\n('b',)\n" in disagreements
    assert "columns: name; 8 rows (truncated at the row cap)\n('0',)\n" in disagreements
    assert "('4',)\n... 3 more\n" in disagreements
    # Agreeing items are not listed, failed or not.
    assert "no such column" not in report


@pytest.mark.phase(1)
def test_report_shows_the_first_twenty_disagreements() -> None:
    failed = ExecResult(ok=False, error='near "x": syntax error', error_kind="syntax")
    scores = [_item(i, "change_literal", False, True, failed) for i in range(25)]

    report = render_report(scores, RUN)

    assert "Disagreeing items: 25 (25 distinct), the first 20 shown below, each once." in report
    assert report.count("\n### ") == 20
    assert "### 20. spider-train-00019 " in report
    assert "spider-train-00020" not in report
    assert 'syntax: near "x": syntax error' in report


@pytest.mark.phase(1)
def test_report_without_disagreements_and_empty_input() -> None:
    ok = ExecResult(ok=True, columns=["name"], rows=[])
    report = render_report([_item(0, "unchanged", True, True, ok)], RUN)
    assert report.endswith("## Disagreements\n\nNone.\n")

    with pytest.raises(ValueError, match="at least one scored item"):
        agreement_rate([])


@pytest.mark.phase(1)
def test_report_counts_repeated_items_once() -> None:
    # An item with an earlier one's database, gold and prediction is the same check again.
    one_row = ExecResult(ok=True, columns=["name"], rows=[("a",)])
    gold_sql = "SELECT DISTINCT name FROM t WHERE x > 1"
    scores = [
        _item(1, "unchanged", True, True, one_row, pred_sql=gold_sql),
        _item(2, "drop_where", True, False, one_row, pred_sql="SELECT name FROM t"),
        _item(3, "unchanged", True, True, one_row, pred_sql=gold_sql),
        _item(4, "drop_where", True, False, one_row, pred_sql="SELECT name FROM t"),
        _item(2, "drop_where", True, False, one_row, pred_sql="SELECT name FROM t"),
        _item(5, "swap_column", False, False, one_row, pred_sql="SELECT x FROM t"),
    ]

    groups = group_repeats(scores)
    assert [[s.mutation.example_id[-1] for s in g] for g in groups] == [
        ["1", "3"],
        ["2", "4", "2"],
        ["5"],
    ]
    # Another database is another check, however alike the SQL.
    elsewhere = ItemScore(
        Mutation("spider-train-00009", "db2", "unchanged", gold_sql, gold_sql),
        *(scores[0].gold, scores[0].pred, False, True, True),
    )
    assert len(group_repeats([scores[0], elsewhere])) == 2

    report = render_report(scores, RUN)

    lines = report.splitlines()
    assert lines[0] == "# Fast and official execution match agree on 50.00% of 6 items"
    assert "| Distinct items | 3 |" in lines
    assert "| Agreement | 50.00% (3 of 6); I5 needs 98% |" in lines
    assert "| Agreement on distinct items | 66.67% (2 of 3) |" in lines
    assert "| fast match | 2 (1) | 3 (1) |" in lines
    assert "| fast no match | 0 (0) | 1 (1) |" in lines
    assert "| drop_where | 3 (1) | 3 (1) | 0 (0) | 3 (1) |" in lines
    assert "| unchanged | 2 (1) | 2 (1) | 2 (1) | 0 (0) |" in lines

    disagreements = report.split("## Disagreements\n", 1)[1]
    assert "Disagreeing items: 3 (1 distinct), each shown once below." in report
    assert disagreements.count("\n### ") == 1
    assert "### 1. spider-train-00002 on db: drop_where, fast match, official no match" in report
    assert (
        "\n3 items have this gold and prediction: "
        "spider-train-00002, spider-train-00004, spider-train-00002.\n"
    ) in disagreements
    assert disagreements.count("items have this gold and prediction") == 1


@pytest.mark.phase(1)
def test_report_carries_the_spider_attribution() -> None:
    report = render_report([_item(0, "unchanged", True, True, ExecResult(ok=True))], RUN)

    attribution = report.split("\n\n")[2]
    assert "Spider 1.0 (Yu et al., EMNLP 2018)" in attribution
    assert "[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/)" in attribution
    # The link resolves from docs/audit, where reports go, to the spike's license section.
    match = re.search(r"\[docs/spikes/data\.md\]\(([^)#]+)#([^)]+)\)", attribution)
    assert match, attribution
    spike = (ROOT / "docs" / "audit" / match.group(1)).resolve()
    assert spike == ROOT / "docs" / "spikes" / "data.md"
    assert match.group(2) == "2-license-and-attribution"
    assert "\n## 2. License and attribution\n" in spike.read_text()
